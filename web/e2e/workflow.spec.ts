import { expect, test } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { readFileSync } from "node:fs";

test("sample LLM, kedua mode, progres tersimpan, koreksi caption, dan unduh", async ({ page, request }) => {
  const browserErrors: string[] = [];
  page.on("pageerror", e => browserErrors.push(e.message));
  await page.goto("/llm");
  await page.getByRole("button", { name: "Jalankan sample LLM" }).click();
  await expect(page.getByTestId("llm-result")).toContainText('"provider": "mock"');
  await page.goto("/");
  await page.getByRole("combobox", { name: "Mode", exact: true }).selectOption("both");
  await page.getByLabel("Jumlah klip").fill("1");
  await page.getByRole("button", { name: "Mulai proses" }).click();
  const clipsLink = page.getByRole("link", { name: "Buka output Klip" });
  const condenseLink = page.getByRole("link", { name: "Buka output Ringkas" });
  await expect(clipsLink).toBeVisible(); await expect(condenseLink).toBeVisible();
  const condensedHref = await condenseLink.getAttribute("href");
  await clipsLink.click();
  await expect(page).toHaveURL(/\/outputs\/[0-9a-f-]+$/);
  await page.reload(); // Worker must survive a page/tab reload.
  await expect(page.getByTestId("output-status")).toHaveText("done", { timeout: 90000 });
  await expect(page.getByTestId("clip-result")).toHaveCount(1);
  await page.getByText("Rincian skor", { exact: true }).click();
  await expect(page.getByText(/Catatan urutan:/)).toBeVisible();
  const detailResponse = await request.get(`/api${new URL(page.url()).pathname}`);
  const selectedDetail = await detailResponse.json();
  expect(selectedDetail.clips[0].thumbnail_url).toBeTruthy();
  const thumbnail = await request.get(selectedDetail.clips[0].thumbnail_url);
  expect(thumbnail.ok()).toBeTruthy();
  expect(thumbnail.headers()["content-type"]).toContain("image/jpeg");
  expect(selectedDetail.clips[0].qc.normalization.status).toBe("two_pass");
  await page.getByText("Pemeriksaan kualitas video", { exact: true }).click();
  await expect(page.getByText("Volume suara: lolos", { exact: true })).toBeVisible();
  const signals = await request.get(`/api/projects/${selectedDetail.project.id}/signals`);
  expect(signals.ok()).toBeTruthy();
  expect((await signals.json()).smoothing_seconds).toBe(5);
  const audit = await request.get(`/api/outputs/${selectedDetail.output.id}/selection`);
  const selectedAudit = await audit.json();
  expect(selectedAudit.status).toBe("complete");
  expect(selectedAudit.metrics.max_per_topic).toBeLessThanOrEqual(2);
  const video = page.locator("video").first();
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.readyState)).toBeGreaterThan(0);
  await page.getByText("Edit judul, hook, dan caption", { exact: true }).click();
  await page.getByText("Ritme video dan sorotan caption", { exact: true }).click();
  await page.getByLabel("Zoom halus pada pembicara", { exact: true }).uncheck();
  await page.getByRole("textbox", { name: "Caption s1", exact: true }).fill("Caption dikoreksi lewat browser.");
  await page.getByRole("button", { name: "Simpan dan render ulang klip" }).click();
  await expect(page.getByTestId("output-status")).toHaveText("done", { timeout: 60000 });
  await expect.poll(async () => {
    const path = new URL(page.url()).pathname;
    const detail = await request.get(`/api${path}`);
    const data = await detail.json();
    return data.clips[0].caption_overrides.s1 === "Caption dikoreksi lewat browser." && !data.clips[0].needs_render;
  }, { timeout: 60000 }).toBe(true);
  const download = page.waitForEvent("download");
  await page.getByRole("link", { name: "Unduh semua hasil (ZIP)" }).click();
  expect((await download).suggestedFilename()).toMatch(/\.zip$/);
  await page.goto(condensedHref!);
  await expect(page.getByTestId("output-status")).toHaveText("awaiting_review", { timeout: 90000 });
  await page.getByLabel("Target durasi (detik)").fill("3");
  await page.getByRole("button", { name: "Setujui bab dan render Ringkas" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Durasi minimum" })).toBeVisible();
  await page.getByLabel("Target durasi (detik)").fill("20");
  await page.getByRole("button", { name: "Hitung durasi tanpa render" }).click();
  await expect(page.getByText(/Rencana hasil:/)).toBeVisible();
  await page.getByRole("button", { name: "Setujui bab dan render Ringkas" }).click();
  await expect(page.getByTestId("output-status")).toHaveText("done", { timeout: 90000 });
  await expect(page.getByRole("link", { name: "Unduh ringkasan MP4" })).toBeVisible();
  await page.goto("/history");
  await expect(page.getByRole("link", { name: "Video demo sintetis" })).toBeVisible();
  expect(browserErrors).toEqual([]);
});

test("glosarium, unggah video dengan sidecar, progres proyek, dan cache transkrip", async ({ page, request }) => {
  execFileSync("../.venv/bin/python", ["../scripts/make_sample.py"]);
  await page.goto("/preferences");
  await page.getByRole("textbox", { name: "Kata yang salah", exact: true }).fill("usaha");
  await page.getByRole("textbox", { name: "Kata yang benar", exact: true }).fill("bisnis");
  await page.getByRole("button", { name: "Simpan istilah" }).click();
  await expect(page.getByText("usaha → bisnis", { exact: false })).toBeVisible();
  await page.goto("/");
  await page.getByRole("combobox", { name: "Jenis sumber", exact: true }).selectOption("upload");
  await page.getByLabel("Berkas video", { exact: true }).setInputFiles(resolve("../examples/sample.mp4"));
  await page.getByLabel("Transkrip JSON bertimestamp (opsional)", { exact: true }).setInputFiles(resolve("../examples/transcript.json"));
  await page.getByRole("combobox", { name: "Bahasa transkripsi", exact: true }).selectOption("id");
  await page.getByRole("button", { name: "Mulai proses" }).click();
  await page.getByRole("link", { name: "Lihat progres sumber dan transkrip" }).click();
  await expect(page.getByTestId("transcript-status")).toHaveText("done", { timeout: 60000 });
  const projectPath = new URL(page.url()).pathname;
  const before = await request.get(`/api${projectPath}/transcript`);
  expect(before.ok()).toBeTruthy();
  expect((await before.json()).sentences[0].text).toContain("bisnis");
  await page.reload();
  await expect(page.getByTestId("transcript-status")).toHaveText("done");
  await expect(page.getByRole("link", { name: "Buka transkrip JSON" })).toBeVisible();
  await page.goto("/preferences");
  await page.getByRole("button", { name: "Hapus istilah usaha", exact: true }).click();
  await expect(page.getByRole("button", { name: "Hapus istilah usaha", exact: true })).toHaveCount(0);
  const after = await request.get(`/api${projectPath}/transcript`);
  expect(await after.json()).toEqual(await before.json());
});

test("preferensi, kata bertimestamp, trim satu klip, format Shorts, dan contoh suka", async ({ page, request }) => {
  const originalPreferences = await (await request.get("/api/preferences")).json();
  try {
    execFileSync("../.venv/bin/python", ["../scripts/make_sample.py"]);
    const file = readFileSync(resolve("../examples/sample.mp4"));
    const uploaded = await request.post("/api/uploads", { data: { filename: "word-tutorial.mp4", total_bytes: file.length } });
    const upload = await uploaded.json();
    expect((await request.put(`/api/uploads/${upload.id}?offset=0`, { data: file, headers: { "Content-Type": "application/octet-stream" } })).ok()).toBeTruthy();
    const entries: [number, number, string][] = [[0.2, 0.6, "Pisahkan"], [0.8, 1.2, "uang"], [2.5, 3.2, "usaha."], [4.2, 4.6, "Catat"], [4.8, 5.2, "setiap"], [7, 7.8, "transaksi."], [8.2, 8.7, "Tinjau"], [10.6, 11.3, "hasil."]];
    const words = entries.map(([start, end, text], i) => ({ id: `w${i+1}`, start, end, text }));
    const sentences = [words.slice(0, 3), words.slice(3, 6), words.slice(6)].map((group, i) => ({ id: `s${i+1}`, start: group[0].start, end: group[group.length-1].end, text: group.map(w => w.text).join(" "), word_ids: group.map(w => w.id) }));
    const project = await (await request.post("/api/projects", { data: { source_kind: "upload", upload_id: upload.id, transcript: { language: "id", words, sentences } } })).json();
    await page.goto("/preferences");
    await page.getByLabel("Jumlah klip bawaan", { exact: true }).fill("2");
    await page.getByLabel("Maksimum klip bawaan (detik)", { exact: true }).fill("4");
    await page.getByRole("combobox", { name: "Platform tujuan", exact: true }).selectOption("youtube_shorts");
    await page.getByLabel("Target ringkasan bawaan (detik)", { exact: true }).fill("9");
    await page.getByRole("button", { name: "Simpan preferensi output", exact: true }).click();
    await expect(page.getByText("Preferensi tersimpan.", { exact: true })).toBeVisible();
    await page.reload();
    await expect(page.getByLabel("Target ringkasan bawaan (detik)", { exact: true })).toHaveValue("9");
    await page.goto(`/projects/${project.id}`);
    await expect(page.getByLabel("Jumlah klip", { exact: true })).toHaveValue("2");
    await expect(page.getByRole("combobox", { name: "Platform tujuan", exact: true })).toHaveValue("youtube_shorts");
    await page.getByRole("button", { name: "Buat output dari proyek ini", exact: true }).click();
    await page.getByRole("link", { name: "Buka output Klip", exact: true }).click();
    await expect(page.getByTestId("output-status")).toHaveText("done", { timeout: 90000 });
    await expect(page.getByTestId("clip-result")).toHaveCount(2);
    const url = `/api${new URL(page.url()).pathname}`;
    const before = await (await request.get(url)).json();
    const firstIndex = before.clips.findIndex((c: { start_s: number }) => c.start_s < 1);
    expect(firstIndex).toBeGreaterThanOrEqual(0);
    const first = before.clips[firstIndex], other = before.clips[1-firstIndex];
    const card = page.getByTestId("clip-result").nth(firstIndex);
    await card.getByText("Edit judul, hook, dan caption", { exact: true }).click();
    await card.getByLabel(/^Kata w2 /).fill("modal");
    await card.getByLabel("Awal klip (detik)", { exact: true }).fill("0.34");
    await card.getByLabel("Akhir klip (detik)", { exact: true }).fill("3.1");
    await card.getByRole("combobox", { name: "Preset caption", exact: true }).selectOption("karaoke");
    await card.getByRole("button", { name: "Simpan dan render ulang klip", exact: true }).click();
    await expect.poll(async () => {
      const fresh = await (await request.get(url)).json();
      return fresh.output.status === "done" && fresh.clips[firstIndex].caption_overrides.w2 === "modal" && fresh.clips[firstIndex].render_fingerprint !== first.render_fingerprint && !fresh.clips[firstIndex].needs_render;
    }, { timeout: 60000 }).toBe(true);
    const after = await (await request.get(url)).json();
    expect(after.clips[firstIndex].start_s).toBe(0.2); expect(after.clips[firstIndex].end_s).toBe(3.2);
    expect(after.clips[firstIndex].qc.karaoke_enabled).toBe(true);
    expect(after.clips[firstIndex].qc.checks.platform_format).toBe(true);
    expect(after.clips[firstIndex].qc.width).toBeLessThan(after.clips[firstIndex].qc.height);
    expect(after.clips[firstIndex].qc.width * 16).toBe(after.clips[firstIndex].qc.height * 9);
    expect(after.clips[1-firstIndex].render_fingerprint).toBe(other.render_fingerprint);
    expect(after.transcript).toEqual(before.transcript);
    await expect(card.locator("video")).toHaveAttribute("src", new RegExp(after.clips[firstIndex].render_fingerprint));
    await expect(card.getByRole("button", { name: "Suka", exact: true })).toBeEnabled();
    await card.getByText("Tambahkan koreksi kata ke glosarium", { exact: true }).click();
    await card.getByRole("button", { name: "Simpan uang → modal ke glosarium", exact: true }).click();
    await expect(card.getByText("Tersimpan.", { exact: true })).toBeVisible();
    await card.getByLabel("Catatan penilaian", { exact: true }).fill("Langkah utuh dan subtitle terbaca");
    await card.getByRole("button", { name: "Suka", exact: true }).click();
    await expect(card.getByRole("button", { name: "Suka", exact: true })).toHaveAttribute("aria-pressed", "true");
    const next = await (await request.post(`/api/projects/${project.id}/outputs`, { data: { mode: "clips", settings: { clip_count: 1 } } })).json();
    await expect.poll(async () => (await (await request.get(`/api/outputs/${next.id}`)).json()).output.status, { timeout: 60000 }).toBe("done");
    const audit = await (await request.get(`/api/outputs/${next.id}/selection`)).json();
    expect(audit.liked_examples_used).toBe(1);
    await page.goto("/preferences");
    await expect(page.getByText("uang → modal", { exact: false })).toBeVisible();
    await page.getByRole("button", { name: "Hapus istilah uang", exact: true }).click();
    await expect(page.getByRole("button", { name: "Hapus istilah uang", exact: true })).toHaveCount(0);
  } finally {
    expect((await request.put("/api/preferences", { data: originalPreferences })).ok()).toBeTruthy();
  }
});
